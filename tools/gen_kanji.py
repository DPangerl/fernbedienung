"""Write the few kanji and kana the Fernbedienung app draws (KAIRO's labels) to a C header, as 1-bit bitmaps from
the Shinonome Gothic BDFs (public domain; assets/fonts/shnmk16.bdf, shnmk12.bdf, from xfonts-shinonome 0.9.11):

  tools/gen_kanji.py        -> firmware/apps/fernbedienung/fb_kanji.h

Only the glyphs listed below go in. Add a character here, rerun, and draw it with fb_kanji_text (fb_kanji.h).
"""
from pathlib import Path

SRC = Path(__file__).resolve().parents[1]
FONTS = SRC / "assets" / "fonts"
OUT = SRC / "firmware" / "apps" / "fernbedienung" / "fb_kanji.h"

# size -> the characters drawn at that size
GLYPHS = {
    16: "こだま曲げ回路",
    12: "木霊消録一二三頭強自励速度発条位相",
}


def jis(ch):
    """the BDF's ENCODING of ch: JIS X 0208, row and cell as one number"""
    b = ch.encode("euc_jp")
    if len(b) != 2:
        raise SystemExit(f"gen_kanji: {ch!r} is not in JIS X 0208")
    return (b[0] - 0x80) << 8 | (b[1] - 0x80)


def load(path):
    """ENCODING -> rows (ints, MSB the left pixel) of a BDF"""
    glyphs, enc, rows, inbits = {}, None, [], False
    for line in path.read_text(encoding="latin-1").splitlines():
        if line.startswith("ENCODING "):
            enc = int(line.split()[1])
        elif line == "BITMAP":
            rows, inbits = [], True
        elif line == "ENDCHAR":
            glyphs[enc], inbits = rows, False
        elif inbits:
            rows.append(int(line, 16))
    return glyphs


def main():
    out = [
        "/* SPDX-License-Identifier: GPL-3.0-only",
        " * Generated by tools/gen_kanji.py from the Shinonome Gothic fonts (public domain, LICENSES/PD-Shinonome.txt):",
        " * do not edit. Each glyph: its code point, its size (px, square), a row per pixel row, bit 15 the left pixel. */",
        "#ifndef FB_KANJI_DATA_H",
        "#define FB_KANJI_DATA_H",
        "",
        "typedef struct {",
        "    uint32_t cp;",
        "    uint8_t size;",
        "    uint16_t rows[16];",
        "} fb_kanji_t;",
        "",
        "static const fb_kanji_t FB_KANJI[] = {",
    ]
    count = 0
    for size, chars in GLYPHS.items():
        font = load(FONTS / f"shnmk{size}.bdf")
        for ch in chars:
            rows = font[jis(ch)]
            if len(rows) != size:
                raise SystemExit(f"gen_kanji: {ch} has {len(rows)} rows, not {size}")
            width_bits = (size + 7) // 8 * 8
            rows = [r << (16 - width_bits) for r in rows] + [0] * (16 - size)
            out.append(f"    {{ 0x{ord(ch):04X}u, {size}, {{ " + ", ".join(f"0x{r:04X}" for r in rows) + f" }} }},   /* {ch} */")
            count += 1
    out += ["};", "", f"#define FB_KANJI_N {count}u", "", "#endif", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"kanji: {count} glyphs -> {OUT.relative_to(SRC)}")


if __name__ == "__main__":
    main()
